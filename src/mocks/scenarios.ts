/**
 * T05 — scenario descriptors, deterministic clocks and ids.
 *
 * The mock layer is split by test context: each scenario owns its own
 * Repository, its own clock origin and its own id counter. E2E specs
 * read `?mi-scenario=<name>` from `location.search` and pass the
 * resulting descriptor to the handler factory so two Playwright
 * contexts cannot leak state into each other.
 *
 * Clock + ids are factory-injected; the factory never falls back to
 * `Date.now()` or `Math.random()` so the same scenario name always
 * produces the same order of generated values.
 */

import { isRecord } from './is-record';

/** Identifier of a scenario as carried in URLs and test fixtures. */
export type ScenarioName = string;

/** A scenario carries the seed, the clock origin and the isolation flag. */
export interface ScenarioDescriptor {
  readonly name: ScenarioName;
  readonly seed: number;
  readonly clockOffsetMs: number;
  readonly isolated: boolean;
}

/** Clock injected into the handler factory. */
export interface Clock {
  /** Returns the current ISO timestamp. */
  now(): string;
  /** Advances the deterministic clock by the given delta. */
  advanceMs(delta: number): void;
}

/** Id factory injected into the handler factory. */
export interface Ids {
  /** Returns a contract-conforming opaque identifier. */
  uuid(): string;
}

/**
 * Pattern from the OpenAPI contract: `X-Demo-Session` and every other
 * generated id must match `^[a-zA-Z0-9_-]{8,80}$`. The same regex
 * guards ids generated by both real and deterministic factories so a
 * snapshot never carries an out-of-contract identifier.
 */
export const ID_PATTERN = /^[a-zA-Z0-9_-]{8,80}$/;

/** Default scenario for the demo UI when no query param is provided. */
export const DEFAULT_SCENARIO: ScenarioDescriptor = Object.freeze({
  name: 'default',
  seed: 1,
  clockOffsetMs: 0,
  isolated: false,
});

/**
 * Built-in scenarios. The registry is frozen at module load; T06–T09
 * register additional entries by adding them to this file (or, if a
 * runtime extension is needed, by going through `resolveScenario`
 * with a new `name`) rather than mutating the exported object.
 */
export const BUILT_IN_SCENARIOS: Readonly<Record<ScenarioName, ScenarioDescriptor | undefined>> =
  Object.freeze({
    default: DEFAULT_SCENARIO,
    'happy-path': Object.freeze({
      name: 'happy-path',
      seed: 101,
      clockOffsetMs: 0,
      isolated: false,
    }),
    'out-of-stock': Object.freeze({
      name: 'out-of-stock',
      seed: 202,
      clockOffsetMs: 0,
      isolated: true,
    }),
    'payment-declined': Object.freeze({
      name: 'payment-declined',
      seed: 303,
      clockOffsetMs: 0,
      isolated: true,
    }),
  });

/**
 * Resolves a scenario by name. Unknown names yield a fresh descriptor
 * whose seed/offset match the default; the name is preserved so log
 * lines and snapshot keys stay accurate. Returning a default shape
 * (never throwing) keeps the bootstrap path safe when an E2E spec
 * passes an out-of-date name.
 */
export function resolveScenario(name: ScenarioName | null | undefined): ScenarioDescriptor {
  if (typeof name !== 'string' || name.length === 0) return DEFAULT_SCENARIO;
  const known = BUILT_IN_SCENARIOS[name];
  if (known) return known;
  return {
    name,
    seed: DEFAULT_SCENARIO.seed,
    clockOffsetMs: DEFAULT_SCENARIO.clockOffsetMs,
    isolated: true,
  };
}

/**
 * True when `value` carries a `location.search` string, the shape
 * `parseScenarioFromLocation` needs. `globalThis` is read as `unknown`
 * first because a Node/SSR runtime has no `location` at all, whatever
 * the DOM lib types assume.
 */
function hasLocationSearch(value: unknown): value is { location: { search: string } } {
  if (!isRecord(value)) return false;
  if (!('location' in value)) return false;
  const location = value['location'];
  if (!isRecord(location)) return false;
  if (!('search' in location)) return false;
  return typeof location['search'] === 'string';
}

/**
 * Reads `?mi-scenario=<name>` from `globalThis.location` when present.
 * Returns the default scenario descriptor when the document lacks
 * `location` (Node, SSR) or the query param is absent.
 */
export function parseScenarioFromLocation(): ScenarioDescriptor {
  const globalScope: unknown = globalThis;
  if (!hasLocationSearch(globalScope)) return DEFAULT_SCENARIO;
  const params = new URLSearchParams(globalScope.location.search);
  return resolveScenario(params.get('mi-scenario'));
}

/**
 * Fixed clock used by deterministic E2E specs. The clock advances by
 * accumulation; `now()` always returns an ISO 8601 timestamp.
 */
export function createFixedClock(initialIso: string): Clock {
  let currentMs = Date.parse(initialIso);
  return {
    now(): string {
      return new Date(currentMs).toISOString();
    },
    advanceMs(delta: number): void {
      currentMs += delta;
    },
  };
}

/**
 * Real clock used by the demo UI. The offset is exposed so a scenario
 * with `clockOffsetMs > 0` can simulate "now" without rewriting the
 * handler factory signature.
 */
export function createRealClock(offsetMs = 0): Clock {
  let delta = offsetMs;
  return {
    now(): string {
      return new Date(Date.now() + delta).toISOString();
    },
    advanceMs(add: number): void {
      delta += add;
    },
  };
}

/**
 * Deterministic id factory. The ids carry the seed in the second
 * segment so debugging remains readable; the counter is zero-padded
 * to four digits so the result is always at least 10 characters
 * long and well above the 8-character contract minimum.
 */
export function createDeterministicIds(seed: number): Ids {
  let counter = 0;
  const idSeed = seed.toString(36);
  return {
    uuid(): string {
      counter += 1;
      const padded = counter.toString().padStart(4, '0');
      const candidate = `e2e-${idSeed}-${padded}`;
      return assertIdPattern(candidate);
    },
  };
}

/**
 * Real id factory backed by `crypto.randomUUID()` with a `Date.now`
 * fallback for environments that lack `crypto`. Every emitted id is
 * validated against the contract pattern before being returned.
 */
export function createRealIds(): Ids {
  return {
    uuid(): string {
      const candidate =
        typeof globalThis.crypto.randomUUID === 'function'
          ? globalThis.crypto.randomUUID()
          : fallbackUuid();
      return assertIdPattern(candidate);
    },
  };
}

function fallbackUuid(): string {
  const time = Date.now().toString(36);
  const rand = Math.random().toString(36).slice(2, 10);
  return `id-${time}-${rand}`;
}

function assertIdPattern(candidate: string): string {
  const trimmed = candidate.trim();
  if (!ID_PATTERN.test(trimmed)) {
    throw new Error(
      `[mi-bolt] generated id violates contract pattern ${ID_PATTERN.source}: ${trimmed}`,
    );
  }
  return trimmed;
}
