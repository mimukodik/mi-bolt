/**
 * T17 — serialized cart mutation queue.
 *
 * The cart facade drives five mutating operations through MSW:
 *   - create cart (no If-Match)
 *   - addCartItem
 *   - setCartItemQuantity
 *   - removeCartItem
 *   - refetch (GET /carts/{id}) after a conflict
 *
 * Every mutation must carry the cart version the server expects.
 * The contract says the version is bound at ACTUAL dispatch, NOT at
 * the moment the user clicked "Add to cart" — so two intents that
 * arrive within the same microtask must be serialized through a
 * single queue, each binding its `If-Match` to the version the
 * server returned by the previous dispatch.
 *
 * The queue is a pure data structure: it knows nothing about the SDK
 * or MSW. The facade plugs a `dispatch(intent, expectedVersion)`
 * function into `enqueue(...)` and the queue guarantees strict
 * serialization, exposes a `pendingCount` signal, and tracks the
 * version between dispatches through the facade's
 * `setVersionProvider` hook.
 *
 * Idempotency keys are generated by the FACADE, not the queue, so
 * the same intent submitted twice can be distinguished from a
 * genuine retry: a fresh intent always carries a new key; a
 * `retry()` call reuses the previously failed intent's key.
 */

import { signal, type Signal, type WritableSignal } from '@angular/core';

import type { Cart } from '../../api/generated/models/cart';
import type { ProblemCode } from '../../api/generated/models/problem-code';

/** Discriminator for every intent the queue can serialize. */
export type MutationIntentKind =
  | 'create'
  | 'addItem'
  | 'setQuantity'
  | 'removeItem'
  | 'refetch';

/**
 * A single mutation request waiting in the queue. The
 * `idempotencyKey` is owned by the facade so retries can reuse it.
 */
export interface MutationIntent {
  readonly kind: MutationIntentKind;
  readonly idempotencyKey: string;
  /** True when this intent is being re-submitted after a 409. */
  readonly retry: boolean;
  readonly payload: Readonly<Record<string, unknown>>;
}

/** Inputs the queue hands to the dispatcher at actual dispatch time. */
export interface DispatchInputs {
  readonly intent: MutationIntent;
  /**
   * Expected cart version bound to this dispatch. Null for the
   * `create` intent and for any `refetch` that does not need
   * optimistic concurrency control.
   */
  readonly expectedVersion: number | null;
}

/** Successful dispatch returns the authoritative cart snapshot. */
export interface SuccessfulDispatch {
  readonly ok: true;
  readonly cart: Cart;
  /** True when the server replayed the cached idempotency body. */
  readonly replayed: boolean;
}

/**
 * 409 / 410 / 404 are terminal for the intent that raised them; any
 * other Problem is wrapped in `other` so the facade can surface a
 * generic error signal without losing the wire-level code.
 */
export type FailedDispatch =
  | { readonly ok: false; readonly code: 'CART_VERSION_CONFLICT'; readonly status: 409; readonly detail: string }
  | { readonly ok: false; readonly code: 'CART_EXPIRED'; readonly status: 410; readonly detail: string }
  | { readonly ok: false; readonly code: 'NOT_FOUND'; readonly status: 404; readonly detail: string }
  | { readonly ok: false; readonly code: ProblemCode; readonly status: number; readonly detail: string };

export type DispatchResult = SuccessfulDispatch | FailedDispatch;

/**
 * Serialized mutation queue. The facade plugs a dispatcher into
 * `enqueue(...)` and the queue guarantees strict, in-order
 * execution with a fresh `expectedVersion` snapshot at each step.
 */
export class CartMutationQueue {
  private readonly pendingWritable: WritableSignal<number> = signal(0);
  /** Readonly queue-depth signal — observed by the facade. */
  readonly pendingCount: Signal<number> = this.pendingWritable.asReadonly();

  private tail: Promise<void> = Promise.resolve();
  private versionProvider: () => number | null = () => null;

  /**
   * Installs the version provider. The provider is called inside
   * the queue's microtask so it always observes the freshest
   * version the facade has acknowledged from the server.
   */
  setVersionProvider(provider: () => number | null): void {
    this.versionProvider = provider;
  }

  /**
   * Serializes `intent` behind every previously enqueued intent.
   * Returns a promise that resolves with the dispatcher result so
   * callers can `await` their own call and observe authoritative
   * state. The dispatcher is invoked with the version provider's
   * CURRENT value, never the value at enqueue time.
   */
  enqueue(
    intent: MutationIntent,
    dispatch: (inputs: DispatchInputs) => Promise<DispatchResult>,
  ): Promise<DispatchResult> {
    this.pendingWritable.update((n) => n + 1);
    const next = this.tail.then(() => {
      const expectedVersion = this.versionProvider();
      return dispatch({ intent, expectedVersion });
    });
    this.tail = next.then(
      () => undefined,
      () => undefined,
    );
    void next.then(
      () => this.pendingWritable.update((n) => n - 1),
      () => this.pendingWritable.update((n) => n - 1),
    );
    return next;
  }

  /**
   * Test seam: lets a test wait for every queued dispatch to
   * settle without depending on wall-clock timers. Production code
   * never calls this; tests that assert on `pendingCount` use it to
   * flush microtasks deterministically.
   */
  async settle(): Promise<void> {
    await this.tail;
  }
}

/** Exposed so tests can wait for the queue to drain. */
export function settleQueue(queue: CartMutationQueue): Promise<void> {
  return queue.settle();
}